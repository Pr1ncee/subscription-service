import uuid
from datetime import UTC, datetime
from decimal import Decimal

import pytest
from alembic import command
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from subscriptions_service.db.tables import NotificationRow, PaymentRow, SubscriptionRow
from tests.support import alembic_config

NOW = datetime(2026, 1, 1, 12, tzinfo=UTC)


def test_migrations_match_models(pg_url: str) -> None:
    command.check(alembic_config(pg_url))  # raises AutogenerateDiffsDetected on drift


def _payment_notification(payment_id: uuid.UUID) -> NotificationRow:
    return NotificationRow(
        id=uuid.uuid4(),
        subscription_id="s1",
        payment_id=payment_id,
        event_name="payment.succeeded",
        scheduled_for=NOW,
        status="scheduled",
    )


async def test_one_result_notification_per_payment(
    session_factory: async_sessionmaker[AsyncSession],
) -> None:
    payment_id = uuid.uuid4()
    async with session_factory() as session:
        session.add(
            SubscriptionRow(
                subscription_id="s1", user_id="u1", day_count=30, expected_expires_on=NOW
            )
        )
        await session.flush()
        session.add(
            PaymentRow(
                id=payment_id,
                subscription_id="s1",
                provider_payment="pp-1",
                amount=Decimal("10"),
                currency="USD",
                status="succeeded",
                period_days=30,
            )
        )
        await session.flush()
        session.add(_payment_notification(payment_id))
        await session.flush()
        session.add(_payment_notification(payment_id))
        with pytest.raises(IntegrityError, match="uq_notifications_payment_id"):
            await session.flush()


@pytest.mark.parametrize(
    ("field", "value", "constraint"),
    [
        ("amount", Decimal("0"), "ck_payments_amount_positive"),
        ("currency", "usd", "ck_payments_currency_iso4217"),
        ("status", "pending", "ck_payments_status_valid"),
        ("period_days", 0, "ck_payments_period_days_positive"),
    ],
)
async def test_payment_check_constraints(
    session_factory: async_sessionmaker[AsyncSession], field: str, value: object, constraint: str
) -> None:
    async with session_factory() as session:
        session.add(
            SubscriptionRow(
                subscription_id="s1", user_id="u1", day_count=30, expected_expires_on=NOW
            )
        )
        await session.flush()
        values: dict[str, object] = {
            "amount": Decimal("10"),
            "currency": "USD",
            "status": "succeeded",
            "period_days": 30,
            field: value,
        }
        session.add(
            PaymentRow(id=uuid.uuid4(), subscription_id="s1", provider_payment="pp-1", **values)
        )
        with pytest.raises(IntegrityError, match=constraint):
            await session.flush()
